const seeds = JSON.parse(readFileSync(new URL('./legacy-content/lesson-seeds.json', import.meta.url), 'utf8')).courses;
const expanded = expandCatalog(seeds, 7200);
const originals = new Map(originalCourses.map(c => [c.id,c]));
export const courses = expanded.map(source => {
  const old = originals.get(source.id);
  const modules = [...(old?.modules || [])];
  for (let i=0; i<source.lessons.length; i+=15) {
    const chunk=source.lessons.slice(i,i+15);
    modules.push({title: `Trilha ${Math.floor(i/15)+1} · ${chunk[0].stage}`, lessons:chunk.map(l=>({
      id:`trilha-${l.number}`, title:l.title, kind:l.kind==='laboratorio'?'project':'lesson',
      explanation:l.explanation, example:l.code, exercise:l.challenge, question:l.question,
      options:l.choices, correct:l.answer, review:l.solution, xp:l.kind==='laboratorio'?35:25
    }))});
  }
  return {...(old || {id:source.id,title:source.name,mark:source.id.slice(0,4).toUpperCase(),description:source.lessons[0].title}), modules};
});
